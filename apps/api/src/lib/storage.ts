class S3StorageDriver implements StorageDriver {
  readonly kind = 's3' as const;

  constructor(
    private readonly client: S3Client,
    private readonly bucket: string,
    private readonly defaultTtl: number,
  ) {}

  async createUploadTicket(input: {
    key: string;
    contentType: string;
    sizeBytes: number;
  }): Promise<UploadTicket> {
    assertValidKey(input.key);
    const command = new PutObjectCommand({
      Bucket: this.bucket,
      Key: input.key,
      ContentType: input.contentType,
      ContentLength: input.sizeBytes,
    });
    const uploadUrl = await getSignedUrl(this.client, command, { expiresIn: this.defaultTtl });
    return {
      key: input.key,
      uploadUrl,
      method: 'PUT',
      headers: {
        'content-type': input.contentType,
        'content-length': String(input.sizeBytes),
      },
      expiresInSeconds: this.defaultTtl,
    };
  }

  async getSignedReadUrl(key: string, ttlSeconds?: number): Promise<string> {
    assertValidKey(key);
    return getSignedUrl(this.client, new GetObjectCommand({ Bucket: this.bucket, Key: key }), {
      expiresIn: ttlSeconds ?? this.defaultTtl,
    });
  }

  async put(key: string, body: Buffer, contentType: string): Promise<void> {
    assertValidKey(key);
    await this.client.send(
      new PutObjectCommand({ Bucket: this.bucket, Key: key, Body: body, ContentType: contentType }),
    );
  }

  async delete(key: string): Promise<void> {
    assertValidKey(key);
    await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }
}

let driver: StorageDriver | null = null;

export function getStorage(): StorageDriver {
  if (driver) return driver;
  const config = getConfig();
  if (config.STORAGE_DRIVER === 's3') {
    const client = new S3Client({
      region: config.S3_REGION ?? 'ap-south-1',
      endpoint: config.S3_ENDPOINT,
      forcePathStyle: config.S3_FORCE_PATH_STYLE,
      credentials:
        config.S3_ACCESS_KEY_ID && config.S3_SECRET_ACCESS_KEY
          ? {
              accessKeyId: config.S3_ACCESS_KEY_ID,
              secretAccessKey: config.S3_SECRET_ACCESS_KEY,
            }
          : undefined,
    });
    driver = new S3StorageDriver(
      client,
      config.S3_BUCKET ?? 'balsanskar',
      config.SIGNED_URL_TTL_SECONDS,
    );
  } else {
    driver = new LocalStorageDriver(
      config.STORAGE_LOCAL_DIR,
      config.PUBLIC_API_BASE_URL,
      config.JWT_SECRET,
      config.SIGNED_URL_TTL_SECONDS,
    );
  }
  return driver;
}

/** Test helper. */
export function resetStorage(): void {
  driver = null;
}
